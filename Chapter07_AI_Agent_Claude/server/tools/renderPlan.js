// Layer 3 / Tool: TestPlan JSON -> the 14-section test plan document. Deterministic, no LLM.
// SOP: architecture/04_render_output.md
//
// Two kinds of content meet here, and keeping them apart is the point:
//
//   TICKET-DERIVED — objective, features, scope, environment, strategy, risks, entry/exit,
//     gaps. Comes from the model, every item traceable to a Jira field.
//   PROCESS BOILERPLATE — defect lifecycle, severity/priority scales, deliverable list,
//     schedule activities, approval table. Fixed organizational standard, supplied here as
//     constants. Asking a model to restate a fixed process is how process drift is introduced.
//
// Anything the ticket cannot supply is rendered as an explicit blank, never as a plausible
// invention (llm.md R-01).

const TBD = '_Not stated in the source — to be confirmed._'

const bullets = (a, fmt = (x) => x) =>
  a?.length ? a.map((x) => `- ${fmt(x)}`).join('\n') : TBD

const sourceNote = (s) =>
  !s ? '' : /^inferred$/i.test(s) ? '  \n  _inferred — not stated in the ticket_' : `  \n  _source: ${s}_`

const SEV = { high: '🔴 High', medium: '🟠 Medium', low: '🟡 Low' }

// --- process boilerplate (organizational standard, not per-ticket) ---------------

const DEFECT_LIFECYCLE = ['New', 'Assigned', 'In Progress', 'Fixed', 'Retest', 'Closed', 'Reopened']
const SEVERITIES = [
  ['Critical', 'Blocks the feature or corrupts data; no workaround.'],
  ['High', 'Major function incorrect; workaround is costly.'],
  ['Medium', 'Function incorrect but a reasonable workaround exists.'],
  ['Low', 'Cosmetic or minor; no functional impact.'],
]
const PRIORITIES = [
  ['P1', 'Fix immediately; blocks the release.'],
  ['P2', 'Fix before release.'],
  ['P3', 'Fix if time allows.'],
  ['P4', 'Backlog.'],
]
const SCHEDULE_ACTIVITIES = [
  'Test Planning', 'Test Case Design', 'Test Execution', 'Regression', 'Closure',
]
const DELIVERABLES = [
  'Test Plan (this document)', 'Test Scenarios', 'Test Cases', 'Requirements Traceability Matrix',
  'Test Execution Report', 'Defect Report', 'Test Summary Report', 'Sign-off Document',
]
const PHASE_CRITERIA = [
  ['Requirement Analysis', ['Requirement available in Jira'], ['Requirement reviewed', 'High-severity questions from §3 answered']],
  ['Test Design', ['Requirement signed off'], ['Test cases written and peer-reviewed']],
  ['Test Execution', ['Stable build deployed', 'Test cases approved'], ['Planned execution complete', 'Defects logged and triaged']],
  ['Test Closure', ['Execution complete', 'Reports prepared'], ['Sign-off received', 'Summary shared']],
]

// --- helpers ---------------------------------------------------------------------

function table(headers, rows, empty = TBD) {
  if (!rows.length) return empty
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map((c) => String(c ?? '').replace(/\|/g, '\\|') || '—').join(' | ')} |`),
  ].join('\n')
}

export function renderMarkdown(plan, issue) {
  const L = []
  const push = (...xs) => L.push(...xs, '')
  const h = (n, t) => push(`## ${n}. ${t}`)

  push(`# Test Plan — ${plan.issue_key}: ${issue.summary}`)
  push('> **Status: DRAFT — pending human review.** Generated from the Jira ticket; not approved',
    '> until a QA owner signs off. Sections marked _Not stated in the source_ are genuine blanks,',
    '> not oversights — the ticket does not contain that information.')
  push('---')

  // 1 -----------------------------------------------------------------------------
  h(1, 'Document Information')
  push(table(['Field', 'Value'], [
    ['Project', issue.key.split('-')[0]],
    ['Requirement', `[${issue.key}](${plan.issue_url})`],
    ['Title', issue.summary],
    ['Issue type', issue.issue_type],
    ['Status', issue.status],
    ['Jira priority', issue.priority],
    ['Components', issue.components?.join(', ') || '—'],
    ['Fix version(s)', issue.fix_versions?.join(', ') || '—'],
    ['Test plan version', '1.0 (generated)'],
    ['Author', `${issue.reporter ?? 'unknown'} (ticket reporter)`],
    ['Reviewer', issue.assignee ?? '_unassigned — to be confirmed_'],
    ['Generated', plan.generated_at],
    ['Generated by', `${plan.model ?? 'groq'} via the B.L.A.S.T. test plan creator`],
    ['Approval date', '_pending_'],
  ]))

  // 2 -----------------------------------------------------------------------------
  h(2, 'Objective')
  push(plan.objective)

  // 3 — gaps deliberately early. R-01 made visible: a reader must see what the ticket
  // failed to say BEFORE reading anything built on top of it.
  h(3, '⚠️ Gaps & Questions for the Author')
  if (plan.gaps?.length) {
    push('These are unanswered by the ticket. Each question is written to be pasted into a Jira',
      'comment unchanged. **Resolve the High rows before executing this plan.**')
    push(table(['#', 'Area', 'Severity', 'Finding', 'Question for the author'],
      plan.gaps.map((g, i) => [i + 1, g.area, SEV[g.severity] ?? g.severity, g.finding, g.question_for_author])))
  } else {
    push('_No gaps recorded._')
  }

  // 4 -----------------------------------------------------------------------------
  h(4, 'Scope')
  push('**In scope**', '', bullets(plan.scope_in, (s) => `${s.item}${sourceNote(s.source)}`))
  push('**Out of scope**', '', bullets(plan.scope_out, (s) => `${s.item}${sourceNote(s.source)}`))

  // 5 -----------------------------------------------------------------------------
  h(5, 'Features to be Tested')
  push(table(['Priority', 'Feature', 'What it covers', 'Source'],
    (plan.features_to_test ?? []).map((f) => [f.priority, f.feature, f.detail, f.source])))

  // 6 -----------------------------------------------------------------------------
  const env = plan.test_environment ?? {}
  h(6, 'Test Environment')
  push('**Environments**', '')
  push(table(['Environment', 'URL', 'Purpose', 'Source'],
    (env.environments ?? []).map((e) => [e.name, '_not stated_', e.purpose, e.source]),
    `${TBD} The ticket names no environment or URL.`))
  push('**Platforms**', '', bullets(env.platforms))
  push('**Browsers**', '', bullets(env.browsers))
  push('**Test data**', '', bullets(env.test_data, (d) => `${d.item}${sourceNote(d.source)}`))

  // 7 -----------------------------------------------------------------------------
  const strat = plan.test_strategy ?? {}
  h(7, 'Test Strategy')
  push('**Design techniques**', '')
  push(table(['Technique', 'Why it applies here'],
    (strat.design_techniques ?? []).map((t) => [t.technique, t.why])))
  push('**Execution phases**', '')
  push(table(['Phase', 'Focus'], (strat.execution_phases ?? []).map((p) => [p.phase, p.focus])))

  // 8 — boilerplate: the activity list is fixed; the dates are not in the ticket.
  h(8, 'Test Schedule')
  push(table(['Activity', 'Planned date', 'Owner', 'Status'],
    SCHEDULE_ACTIVITIES.map((a) => [a, '_TBD_', '_TBD_', 'Not started'])))
  push('_Dates and owners are not derivable from a Jira ticket. Fill these in during planning._')

  // 9 — boilerplate
  h(9, 'Test Deliverables')
  push(bullets(DELIVERABLES))
  push('_Detailed test cases are a deliverable of this plan, not part of it. Write them once the',
    'High-severity gaps in §3 are resolved._')

  // 10 ----------------------------------------------------------------------------
  h(10, 'Entry & Exit Criteria')
  push(table(['Phase', 'Entry', 'Exit'],
    PHASE_CRITERIA.map(([phase, entry, exit]) => [phase, entry.join('; '), exit.join('; ')])))
  if (plan.entry_criteria?.length || plan.exit_criteria?.length) {
    push(`**Specific to ${plan.issue_key}**`, '')
    push('_Entry_', '', bullets(plan.entry_criteria))
    push('_Exit_', '', bullets(plan.exit_criteria))
  }

  // 11 — boilerplate, except what the ticket actually tells us
  h(11, 'Defect Management')
  push(`**Lifecycle:** ${DEFECT_LIFECYCLE.join(' → ')}`)
  push(`**Tracking tool:** Jira (\`${plan.issue_url.replace(/\/browse\/.*$/, '')}\`)`)
  push('**Severity**', '', table(['Severity', 'Definition'], SEVERITIES))
  push('**Priority**', '', table(['Priority', 'Definition'], PRIORITIES))

  // 12 ----------------------------------------------------------------------------
  h(12, 'Risks & Mitigation')
  push(table(['Risk', 'Impact', 'Likelihood', 'Mitigation', 'Source'],
    (plan.risks ?? []).map((r) => [r.risk, r.impact, r.likelihood, r.mitigation, r.source])))

  // 13 ----------------------------------------------------------------------------
  h(13, 'Roles & Responsibilities')
  push(table(['Role', 'Name', 'Responsibility'], [
    ['QA Lead', '_TBD_', 'Planning, reporting, sign-off'],
    ['Test Engineer', '_TBD_', 'Test design and execution'],
    ['Developer', issue.assignee ?? '_TBD_', 'Implementation and defect fixes'],
    ['Reporter / Product Owner', issue.reporter ?? '_TBD_', 'Requirement clarification (see §3)'],
  ]))
  push('_Only the names carried by the Jira ticket are filled in; the rest are for the QA lead to assign._')

  // 14 ----------------------------------------------------------------------------
  h(14, 'Assumptions')
  push(bullets(plan.assumptions))

  h(15, 'Approvals')
  push(table(['Name', 'Role', 'Signature', 'Date'],
    [['', 'QA Lead', '', ''], ['', 'Product Owner', '', ''], ['', 'Engineering Lead', '', '']]))

  push('---')
  push('### Human review gate', '',
    `- **Unanswered questions blocking sign-off:** ${plan.gaps?.filter((g) => g.severity === 'high').length ?? 0} High-severity gap(s) in §3.`,
    '- **Everything marked _inferred_** was reasoned from context, not stated in the ticket.',
    '- ▶ **Approve or edit this plan before writing test cases or automation.**')
  push(`_Generated by the B.L.A.S.T. Test Plan Creator from [${plan.issue_key}](${plan.issue_url})._`)

  return L.join('\n').replace(/\n{3,}/g, '\n\n').trim() + '\n'
}
